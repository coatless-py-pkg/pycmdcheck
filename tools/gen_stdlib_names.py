#!/usr/bin/env python3
"""Regenerate ``src/pycmdcheck/_stdlib_names.py``.

The imports and dependencies checks must recognise a standard-library module
whatever interpreter pycmdcheck happens to run on. ``tomllib`` is standard on
3.11 and later, ``distutils`` only up to 3.11, and a package that guards such
an import by version is correct on both sides. So the checks use one static
set: the union of ``sys.stdlib_module_names`` over every CPython release this
script can find, plus a short hand-kept list for names that attribute cannot
supply.

Usage::

    python tools/gen_stdlib_names.py            # find interpreters, rewrite the file
    python tools/gen_stdlib_names.py --check    # exit 1 if the file is out of date
    python tools/gen_stdlib_names.py /path/to/python3.15 /path/to/python3.16

Names are only ever added. The script merges what it finds into the names the
file already holds, so running it on a machine that lacks an old interpreter
loses nothing. Run it when a new CPython feature release appears.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "src" / "pycmdcheck" / "_stdlib_names.py"

# Feature releases to look for when no interpreter is named on the command line.
# sys.stdlib_module_names exists from 3.10 on.
CANDIDATE_MINORS = range(10, 20)

# Names that sys.stdlib_module_names on 3.10 or later cannot supply.
EXTRA_NAMES: frozenset[str] = frozenset(
    {
        # Not real modules, but always importable or only seen by type checkers.
        "__main__",
        "_typeshed",
        # PyPy's built-in helper module.
        "__pypy__",
        # Documented standard-library package that CPython leaves out of
        # sys.stdlib_module_names (https://docs.python.org/3/library/test.html).
        "test",
        # In the Python 3.8 module index, removed in 3.9.
        "_dummy_thread",
        "dummy_threading",
        # In the Python 3.8 and 3.9 module indexes, removed in 3.10.
        "formatter",
        "parser",
        "symbol",
        # Private modules present in CPython 3.9.6, removed in 3.10.
        "_bootlocale",
        "_peg_parser",
        # New in Python 3.15 (PEP 799), per the 3.15 module index.
        "profiling",
    }
)

PROBE = (
    "import json, sys; "
    "print(json.dumps({'version': '%d.%d' % sys.version_info[:2], "
    "'names': sorted(getattr(sys, 'stdlib_module_names', ()))}))"
)

HEADER = '''"""Standard-library module names across CPython releases.

Generated by ``tools/gen_stdlib_names.py``. Do not edit by hand. To add a name
that no interpreter reports, add it to ``EXTRA_NAMES`` in that script and run
it again.
"""

'''


def version_key(version: str) -> tuple[int, ...]:
    """Return a sort key that orders "3.9" before "3.10"."""
    return tuple(int(part) for part in version.split("."))


def probe(interpreter: str) -> tuple[str, set[str]] | None:
    """Ask one interpreter for its version and standard-library module names.

    Args:
        interpreter: Path to a Python executable.

    Returns:
        A ``(version, names)`` pair, or ``None`` when the interpreter could not
        be run or is older than 3.10.
    """
    try:
        proc = subprocess.run(
            [interpreter, "-I", "-c", PROBE],
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"skipped {interpreter}: {exc}", file=sys.stderr)
        return None
    if proc.returncode != 0:
        print(f"skipped {interpreter}: exit code {proc.returncode}", file=sys.stderr)
        return None
    try:
        payload = json.loads(proc.stdout)
    except ValueError:
        print(f"skipped {interpreter}: unexpected output", file=sys.stderr)
        return None
    names = set(payload["names"])
    if not names:
        print(
            f"skipped {interpreter}: Python {payload['version']} has no "
            "sys.stdlib_module_names (needs 3.10 or later)",
            file=sys.stderr,
        )
        return None
    return str(payload["version"]), names


def discover_interpreters() -> list[str]:
    """Return the CPython executables installed on this machine.

    Looks on ``PATH`` for each ``python3.N`` and asks ``uv python find`` when
    uv is installed. Nothing is downloaded. Two paths may name the same
    release, which the caller sorts out by the version each one reports.
    """
    found: list[str] = []
    uv = shutil.which("uv")
    env = {**os.environ, "UV_PYTHON_DOWNLOADS": "never"}
    for minor in CANDIDATE_MINORS:
        on_path = shutil.which(f"python3.{minor}")
        if on_path:
            found.append(on_path)
        if uv is None:
            continue
        try:
            proc = subprocess.run(
                [uv, "python", "find", f"3.{minor}"],
                capture_output=True,
                text=True,
                timeout=60,
                check=False,
                env=env,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        path = proc.stdout.strip()
        if proc.returncode == 0 and path:
            found.append(path)
    return list(dict.fromkeys(found))


def read_existing(path: Path) -> tuple[set[str], set[str]]:
    """Read the names and versions the generated file already holds.

    Args:
        path: The generated module.

    Returns:
        A ``(names, versions)`` pair. Both are empty when the file is missing
        or cannot be read as generated.
    """
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError, ValueError):
        return set(), set()
    names: set[str] = set()
    versions: set[str] = set()
    for node in tree.body:
        if not isinstance(node, ast.AnnAssign) or not isinstance(node.target, ast.Name):
            continue
        if node.value is None:
            continue
        try:
            if node.target.id == "STDLIB_MODULE_NAMES":
                call = node.value
                if isinstance(call, ast.Call) and call.args:
                    names = set(ast.literal_eval(call.args[0]))
            elif node.target.id == "GENERATED_FROM":
                versions = set(ast.literal_eval(node.value))
        except (ValueError, TypeError):
            continue
    return names, versions


def render(names: set[str], versions: set[str]) -> str:
    """Return the text of the generated module.

    The layout matches ``ruff format``, so the file passes the format check
    without a second tool run.
    """
    lines = [
        "# CPython feature releases whose sys.stdlib_module_names went into the set.",
        "GENERATED_FROM: tuple[str, ...] = (",
        *(f'    "{version}",' for version in sorted(versions, key=version_key)),
        ")",
        "",
        "STDLIB_MODULE_NAMES: frozenset[str] = frozenset(",
        "    {",
        *(f'        "{name}",' for name in sorted(names)),
        "    }",
        ")",
        "",
    ]
    return HEADER + "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Run the generator.

    Returns:
        0 on success, 1 when ``--check`` finds the file out of date or no
        usable interpreter was found.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "interpreters",
        nargs="*",
        help="Python executables to read (default: every python3.N found)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the file would change",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="file to write (default: %(default)s)",
    )
    args = parser.parse_args(argv)

    existing_names, existing_versions = read_existing(args.output)
    names = set(existing_names) | EXTRA_NAMES
    versions = set(existing_versions)

    seen: set[str] = set()
    for interpreter in args.interpreters or discover_interpreters():
        result = probe(interpreter)
        if result is None:
            continue
        version, found = result
        if version not in seen:
            print(f"Python {version}: {len(found)} names ({interpreter})")
        seen.add(version)
        versions.add(version)
        names |= found

    if not versions:
        print("No interpreter with sys.stdlib_module_names was found.", file=sys.stderr)
        return 1

    text = render(names, versions)
    try:
        current = args.output.read_text(encoding="utf-8")
    except OSError:
        current = ""

    added = sorted(names - existing_names)
    if text == current:
        print(f"{args.output} is up to date ({len(names)} names).")
        return 0
    if args.check:
        print(f"{args.output} is out of date.", file=sys.stderr)
        if added:
            print(f"Missing names: {', '.join(added)}", file=sys.stderr)
        return 1
    args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {args.output} ({len(names)} names).")
    if added and existing_names:
        print(f"Added: {', '.join(added)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
