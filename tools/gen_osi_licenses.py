#!/usr/bin/env python3
"""Regenerate ``src/pycmdcheck/_osi_licenses.py``.

The license check says whether a declared license is approved by the Open
Source Initiative. It takes the answer from the SPDX license list, which marks
every license identifier with ``isOsiApproved``. This script reads that list
and writes the identifiers into a module, so that the check needs no network.

Usage::

    python tools/gen_osi_licenses.py                 # download the list, write the file
    python tools/gen_osi_licenses.py licenses.json   # read a saved copy instead
    python tools/gen_osi_licenses.py --check         # exit 1 if the file is out of date

Deprecated identifiers such as ``GPL-3.0`` are kept, because projects still
declare them. Run the script when a new SPDX license list is released.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "src" / "pycmdcheck" / "_osi_licenses.py"
DEFAULT_SOURCE = "https://spdx.org/licenses/licenses.json"

HEADER = '''"""License identifiers of the SPDX license list.

Generated by ``tools/gen_osi_licenses.py``. Do not edit by hand. An identifier
that the list does not mark as approved by the Open Source Initiative, but that
the license check should accept, goes into ``checks/license.py``.
"""

'''


def load(source: str) -> dict[str, Any]:
    """Read the SPDX license list.

    Args:
        source: An https URL, or the path of a saved copy of the JSON file.

    Returns:
        The decoded document.
    """
    if source.startswith("https://"):
        with urllib.request.urlopen(source, timeout=60) as response:
            text = response.read().decode("utf-8")
    else:
        text = Path(source).read_text(encoding="utf-8")
    document = json.loads(text)
    if not isinstance(document, dict):
        raise ValueError("the SPDX license list is not a JSON object")
    return document


def read_list(document: dict[str, Any]) -> tuple[str, set[str], set[str]]:
    """Pick the identifiers out of the SPDX license list.

    Args:
        document: The decoded ``licenses.json``.

    Returns:
        A ``(version, identifiers, approved)`` triple: the version of the
        list, every license identifier in it, and the ones marked as approved
        by the Open Source Initiative. Deprecated identifiers are in both.
    """
    licenses = document["licenses"]
    identifiers = {str(entry["licenseId"]) for entry in licenses}
    approved = {
        str(entry["licenseId"]) for entry in licenses if entry.get("isOsiApproved")
    }
    return str(document["licenseListVersion"]), identifiers, approved


def render(version: str, identifiers: set[str], approved: set[str]) -> str:
    """Return the text of the generated module.

    The layout matches ``ruff format``, so the file passes the format check
    without a second tool run.
    """
    lines = [
        "# Version of the SPDX license list the identifiers were read from.",
        f'SPDX_LIST_VERSION: str = "{version}"',
        "",
        "# Every license identifier of the list, deprecated ones included.",
        "SPDX_LICENSE_IDS: frozenset[str] = frozenset(",
        "    {",
        *(f'        "{identifier}",' for identifier in sorted(identifiers)),
        "    }",
        ")",
        "",
        "# The identifiers the list marks as approved by the Open Source Initiative.",
        "OSI_APPROVED_LICENSES: frozenset[str] = frozenset(",
        "    {",
        *(f'        "{identifier}",' for identifier in sorted(approved)),
        "    }",
        ")",
        "",
    ]
    return HEADER + "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Run the generator.

    Returns:
        0 on success, 1 when ``--check`` finds the file out of date or the
        license list could not be read.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "source",
        nargs="?",
        default=DEFAULT_SOURCE,
        help="URL or path of the SPDX licenses.json (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the file would change",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="file to write (default: %(default)s)",
    )
    args = parser.parse_args(argv)

    try:
        version, identifiers, approved = read_list(load(args.source))
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"Could not read {args.source}: {exc!r}", file=sys.stderr)
        return 1
    if not approved:
        print(f"{args.source} marks no license as OSI approved.", file=sys.stderr)
        return 1

    text = render(version, identifiers, approved)
    try:
        current = args.output.read_text(encoding="utf-8")
    except OSError:
        current = ""

    summary = (
        f"SPDX license list {version}: {len(identifiers)} identifiers, "
        f"{len(approved)} OSI approved"
    )
    if text == current:
        print(f"{args.output} is up to date ({summary}).")
        return 0
    if args.check:
        print(f"{args.output} is out of date ({summary}).", file=sys.stderr)
        return 1
    args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {args.output} ({summary}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
